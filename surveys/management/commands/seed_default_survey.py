class Command(BaseCommand):
    help = "Create the first customer questionnaire once."

    def handle(self, *args, **options):
        survey, created = Survey.objects.get_or_create(
            slug="joint-project-risk-diagnosis",
            defaults={
                "title": "联营项目全过程风险管理体系诊断表",
                "description": "本诊断用于了解贵司联营、合作施工及类似项目的实际管理现状，为后续风险诊断、管理优化及专项服务方案提供基础。",
                "success_message": "您的填写内容已安全提交。工作人员将在后台完成分析，并按预留联系方式与您沟通。",
                "is_published": True,
            },
        )
        if not created:
            self.stdout.write("Default survey already exists; skipped.")
            return
        Question.objects.bulk_create(
            [
                Question(
                    survey=survey,
                    order=index,
                    section=section,
                    label=label,
                    question_type=question_type,
                    required=required,
                    options=options,
                    help_text=help_text,
                )
                for index, (section, label, question_type, required, options, help_text) in enumerate(default_questions(), 1)
            ]
        )
        self.stdout.write(self.style.SUCCESS("Created default survey with 44 questions."))
